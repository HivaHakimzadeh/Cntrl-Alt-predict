"""One-click final run: evaluates everything and writes the results files.

    python scripts/run_all.py                 # evaluate with the shipped model (models/)
    python scripts/run_all.py --retrain       # first rebuild eval_real.jsonl (if ../datasets exists) and retrain

Outputs (open these for your slides):
    results/REPORT.md          human-readable summary
    results/real_results.csv   unseen-data rows (hand-written + synthetic held-out)
    results/real_cv_results.json   cross-validated real-benchmark numbers + threshold sweep (from src/train_real.py)
"""
import csv, json, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from src import synth                                        # noqa: E402
from src.evaluate import load_rows, predict, summarize       # noqa: E402

if "--retrain" in sys.argv:
    if (ROOT.parent / "datasets").exists():
        subprocess.run([sys.executable, str(ROOT / "scripts" / "load_real_benchmarks.py")], check=True)
    from src import train_real                               # noqa: E402
    train_real.run(verbose=False)

cv_path = ROOT / "results" / "real_cv_results.json"
if not cv_path.exists():
    from src import train_real                               # noqa: E402
    train_real.run(verbose=False)
cv = json.loads(cv_path.read_text())

# data the shipped model never trained on
sets = {"hand-written (40)": load_rows(ROOT / "data" / "eval_handwritten.jsonl"),
        "synthetic held-out (1000)": synth.generate(1000, seed=8, phrasing="novel")}
table = []
for name, rows in sets.items():
    for mode in ("rules", "rules+ml"):
        s = summarize(predict(rows, mode))
        table.append({"dataset": name, "pipeline": mode, **{k: round(v, 3) for k, v in s.items()}})
        print(f"{name:28s} {mode:9s} catch={s['attack_catch_rate']:.1%}  FP={s['false_positive_rate']:.1%}")

res = ROOT / "results"
with open(res / "real_results.csv", "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(table[0].keys())); w.writeheader(); w.writerows(table)

pct = lambda v: "n/a" if v is None else f"{v:.0%}"
d = cv["default_thresholds_30_70"]
md = ["# Results", "",
      "Generated by `scripts/run_all.py` and `src/train_real.py`.", "",
      "## 1. Real benchmarks (out-of-fold: the model never saw the samples it is scored on)", "",
      f"Protocol: {cv['protocol']}. Default thresholds: ALLOW < 30, BLOCK >= 70.", "",
      "| Test set | Pipeline | Attacks caught | Hard-blocked | False positives |", "|---|---|---|---|---|",
      f"| AgentInjectionBench (142 attacks / 40 benign) | rules only | {pct(cv['rules_only_AIB']['attack_catch'])} | {pct(cv['rules_only_AIB']['attack_hard_block'])} | {pct(cv['rules_only_AIB']['false_positive'])} |",
      f"| AgentInjectionBench (142 attacks / 40 benign) | rules+ML (cross-validated) | {pct(d['AIB']['attack_catch'])} | {pct(d['AIB']['attack_hard_block'])} | {pct(d['AIB']['false_positive'])} |",
      f"| InjecAgent held-out ({d['IA_heldout']['n_attack']} attacks / {d['IA_heldout']['n_benign']} synthetic controls) | rules+ML | {pct(d['IA_heldout']['attack_catch'])} | {pct(d['IA_heldout']['attack_hard_block'])} | {pct(d['IA_heldout']['false_positive'])} |",
      "", "Headline false-positive number = the AgentInjectionBench row (40 real benign samples). The InjecAgent controls are",
      "synthetic and easy, so their false-positive rate flatters the model.", "",
      "## 2. Threshold trade-off (out-of-fold)", "",
      "| ALLOW below | AIB attacks caught | AIB false positives | InjecAgent attacks caught |", "|---|---|---|---|"]
for s in cv["threshold_sweep"]:
    md.append(f"| {s['allow_below']} | {pct(s['AIB']['attack_catch'])} | {pct(s['AIB']['false_positive'])} | {pct(s['IA_heldout']['attack_catch'])} |")
md += ["", "## 3. Synthetic and hand-written sets (shipped model, data it never trained on)", "",
       "| Dataset | Pipeline | Attacks caught | Hard-blocked | False positives | False hard-blocks |", "|---|---|---|---|---|---|"]
for r in table:
    md.append(f"| {r['dataset']} | {r['pipeline']} | {pct(r['attack_catch_rate'])} | {pct(r['attack_block_rate'])} | "
              f"{pct(r['false_positive_rate'])} | {pct(r['false_block_rate'])} |")
md += ["", "## Honest notes", "",
       "- Real benchmarks give no tool arguments, so amount/recipient rules have little to act on; the ML text layer does most of the work there.",
       "- Tool names are mapped onto risk classes by `src/tool_registry.py`. Before that mapping, unseen tools were quarantined by default (78% false positives on real benign data).",
       "- AgentInjectionBench is small (182) and hand-crafted with similar templates, so cross-validated numbers may be optimistic.",
       "- The shipped model is retrained on all real data, so quote the cross-validated numbers, not its scores on the same samples."]
(res / "REPORT.md").write_text("\n".join(md), encoding="utf-8")
print("\nWrote results/REPORT.md, real_results.csv (+ real_cv_results.json)")
